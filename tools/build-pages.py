#!/usr/bin/env python3
"""Build the per-section pages for johnnyskyride.com (GitHub Pages).

WORKFLOW: index.html is the single source of truth. After editing index.html,
run this script from the repo root (or anywhere):

    python3 tools/build-pages.py

then commit index.html AND every generated file (articles/, music/, imagery/,
sessions/, members/, store/ index.html, and 404.html) together.

What it does:
  * Reads the section config from the <script type="application/json" id="jsr-pages">
    block in index.html (path, title, description, og image per section). Edit
    titles/descriptions/images there, not in the generated files.
  * Rewrites the meta block between <!-- jsr:meta ... --> and <!-- /jsr:meta -->
    (title, description, canonical, Open Graph, Twitter card) in index.html for "home".
  * Writes <slug>/index.html for every other section: the same page with that
    section's meta block, <meta name="jsr-start"> set, and that section marked as the
    visible page, so link-preview crawlers (which don't run JS) see the right tags,
    and direct loads of /music/ etc. open the right section.
  * Writes 404.html, which forwards unknown paths to the matching section or home, and share
    links (/p/, /c/, /ac/) that tools/build-shares.py hasn't built yet straight to the item.
All asset/script paths in index.html must be root-absolute (/assets/...), because the
same HTML is served from sub-directories.
"""
import html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORIGIN = "https://johnnyskyride.com"
SRC = os.path.join(ROOT, "index.html")

def esc(v): return html.escape(v, quote=True)

def meta_block(key, p):
    url = ORIGIN + p["path"]; img = ORIGIN + p["image"]
    t, d, alt = esc(p["title"]), esc(p["description"]), esc(p.get("alt", p["title"]))
    return "\n".join([
        "<!-- jsr:meta (generated by tools/build-pages.py from #jsr-pages; do not edit by hand) -->",
        f"<title>{t}</title>",
        f'<meta name="description" content="{d}">',
        f'<meta name="jsr-start" content="{key}">',
        f'<link rel="canonical" href="{url}">',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="Johnny Skyride">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:title" content="{t}">',
        f'<meta property="og:description" content="{d}">',
        f'<meta property="og:image" content="{img}">',
        f'<meta property="og:image:secure_url" content="{img}">',
        f'<meta property="og:image:type" content="{"image/png" if p["image"].endswith(".png") else "image/jpeg"}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{alt}">',
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:site" content="@johnnyskyride">',
        '<meta name="twitter:creator" content="@johnnyskyride">',
        f'<meta name="twitter:title" content="{t}">',
        f'<meta name="twitter:description" content="{d}">',
        f'<meta name="twitter:image" content="{img}">',
        f'<meta name="twitter:image:alt" content="{alt}">',
        "<!-- /jsr:meta -->",
    ])

META_RE = re.compile(r"<!-- jsr:meta.*?<!-- /jsr:meta -->", re.S)

def set_start(doc, key):
    # mark only this section as visible, and its nav buttons active (JS does the same at runtime)
    doc = re.sub(r'<section class="page on" id="', '<section class="page" id="', doc)
    doc, n = re.subn(rf'<section class="page" id="{re.escape(key)}"', f'<section class="page on" id="{key}"', doc, count=1)
    if n != 1: sys.exit(f"section #{key} not found in index.html")
    doc = re.sub(r'(<button class="nav-btn) active(" data-page=)', r"\1\2", doc)
    doc = doc.replace(f'<button class="nav-btn" data-page="{key}">', f'<button class="nav-btn active" data-page="{key}">')
    doc = re.sub(r'<button class="active" data-page="([a-z]+)">', r'<button data-page="\1">', doc)
    doc = doc.replace(f'<button data-page="{key}">', f'<button class="active" data-page="{key}">')
    return doc

NOT_FOUND = """<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Johnny Skyride</title><meta name="robots" content="noindex">
<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png">
<style>html,body{margin:0;background:#000;color:#e7e9ea;font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif}a{color:#ff6bb5}p{padding:40px 16px;text-align:center}</style>
<script>
(function(){
  var paths = %s;
  var parts = location.pathname.split("/").filter(Boolean);
  var seg = (parts[0] || "").toLowerCase();
  // share links (/p/<id>/, /c/<id>/, /ac/<id>/) whose stub page isn't built yet: go straight to the item
  var share = { p: "post-", c: "c-", ac: "ac-" }[seg];
  if (share && parts[1] && /^[A-Za-z0-9_-]+$/.test(parts[1])) { location.replace("/#" + share + parts[1]); return; }
  var dest = paths.indexOf("/" + seg + "/") >= 0 ? "/" + seg + "/" : "/";
  location.replace(dest + location.search + location.hash);
})();
</script></head>
<body><p>Taking you to <a href="/">johnnyskyride.com</a>…</p></body></html>
"""

def main():
    src = open(SRC, encoding="utf-8").read()
    m = re.search(r'<script type="application/json" id="jsr-pages">(.*?)</script>', src, re.S)
    if not m: sys.exit("jsr-pages config not found in index.html")
    pages = json.loads(m.group(1))
    if not META_RE.search(src): sys.exit("jsr:meta markers not found in index.html")
    home = META_RE.sub(lambda _: meta_block("home", pages["home"]), src, count=1)
    home = set_start(home, "home")
    if home != src:
        open(SRC, "w", encoding="utf-8").write(home)
    written = ["index.html"]
    for key, p in pages.items():
        if key == "home": continue
        slug = p["path"].strip("/")
        if not re.fullmatch(r"[a-z0-9-]+", slug): sys.exit(f"bad path for {key}: {p['path']}")
        doc = META_RE.sub(lambda _: meta_block(key, p), home, count=1)
        doc = set_start(doc, key)
        os.makedirs(os.path.join(ROOT, slug), exist_ok=True)
        open(os.path.join(ROOT, slug, "index.html"), "w", encoding="utf-8").write(doc)
        written.append(f"{slug}/index.html")
    paths = json.dumps([p["path"] for k, p in pages.items() if k != "home"])
    open(os.path.join(ROOT, "404.html"), "w", encoding="utf-8").write(NOT_FOUND % paths)
    written.append("404.html")
    print("wrote: " + ", ".join(written))

if __name__ == "__main__":
    main()
